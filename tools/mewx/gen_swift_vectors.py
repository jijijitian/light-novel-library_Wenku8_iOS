#!/usr/bin/env python3
"""Regenerates `Tests/Wenku8CoreTests/RelayV2Vectors.swift` from `vectors.json`.

The Swift test suite cannot read the JSON at runtime — the vector set has to be part
of the test bundle so the sealed-envelope port is validated against exactly the bytes
the emulated Android library produced. Keeping one generator means the two never drift:
change the oracle, re-run this script, and the test data follows.

Usage:
    python3 tools/mewx/gen_swift_vectors.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
VECTORS = os.path.join(HERE, 'vectors.json')
OUT = os.path.join(ROOT, 'Tests', 'Wenku8CoreTests', 'RelayV2Vectors.swift')

PER_LINE = 16


def byte_lines(data: bytes, indent: str) -> str:
    """Renders bytes as `0x..` literals, `PER_LINE` per line."""
    out = []
    for start in range(0, len(data), PER_LINE):
        chunk = data[start:start + PER_LINE]
        out.append(indent + ', '.join('0x%02x' % b for b in chunk) + ',')
    return '\n'.join(out)


def describe(body: bytes) -> str:
    """A short, safe name for the case: the action when it is text."""
    try:
        text = body.decode('utf-8')
    except UnicodeDecodeError:
        return '<binary>'
    if text.startswith('action='):
        return text.split('&')[0][len('action='):]
    return text[:24]


def main() -> None:
    with open(VECTORS) as handle:
        vectors = json.load(handle)

    lines = [
        '// Generated by tools/mewx/gen_swift_vectors.py — do not edit by hand.',
        '//',
        '// Each case is one call to the emulated Android library: the plaintext action',
        '// string, the "extra" string the client binds into the envelope, the clock',
        '// correction, and the exact bytes the library returned. Bodies and extras are',
        '// byte arrays rather than strings because a few vectors are deliberately binary.',
        '',
        'enum RelayV2Vectors {',
        '    struct Case {',
        '        let name: String',
        '        let body: [UInt8]',
        '        let extra: [UInt8]',
        '        let counter: Int64',
        '        /// Milliseconds since the epoch that the sealing routine observed.',
        '        let clockMilliseconds: Int64',
        '        /// The envelope the library produced.',
        '        let sealed: [UInt8]',
        '    }',
        '',
        '    static let all: [Case] = [',
    ]

    for index, vector in enumerate(vectors):
        body = bytes.fromhex(vector['body_hex'])
        extra = bytes.fromhex(vector['extra_hex'])
        clock_ms = int(vector['clock_seconds']) * 1000
        name = '%d %s' % (index, describe(body))
        # The oracle recorded this counter as unsigned. Reinterpret the same 64 bits
        # as signed, which is what the sealing routine actually receives.
        counter = int(vector['counter'])
        if counter >= 1 << 63:
            counter -= 1 << 64

        lines.append('        Case(')
        lines.append('            name: %s,' % json.dumps(name))
        lines.append('            body: [')
        lines.append(byte_lines(body, '                ') or '                ')
        lines.append('            ],')
        lines.append('            extra: [')
        lines.append(byte_lines(extra, '                '))
        lines.append('            ],')
        lines.append('            counter: %d,' % counter)
        lines.append('            clockMilliseconds: %d,' % clock_ms)
        lines.append('            sealed: [')
        lines.append(byte_lines(bytes.fromhex(vector['sealed']), '                '))
        lines.append('            ]')
        lines.append('        ),')

    lines += [
        '    ]',
        '',
        '    /// The deterministic entropy every vector was generated with:',
        '    /// `bytes(range(256)) * 16`. The library reads it for the nonce and padding,',
        '    /// so reproducing it here is what makes the nonce identical.',
        '    static let entropy: [UInt8] = {',
        '        var bytes = [UInt8]()',
        '        bytes.reserveCapacity(4096)',
        '        for _ in 0..<16 { bytes.append(contentsOf: 0...255) }',
        '        return bytes',
        '    }()',
        '}',
        '',
    ]

    with open(OUT, 'w') as handle:
        handle.write('\n'.join(lines))
    print('wrote %d vectors to %s' % (len(vectors), OUT))


if __name__ == '__main__':
    main()
