import Foundation

/// The relay v2 envelope's key schedule.
///
/// This is the recovered derivation the official Android client performs in its native
/// library. It is reproduced here in pure Swift, with no C dependency, for two reasons:
/// the core module must still build on Linux for the parser tests, and the derivation is
/// short enough to audit in one place.
///
/// Every step below was verified byte-for-byte against the native library's own internal
/// state, so `sessionKey` reproduces what the client holds in memory after `init()`.
/// See `docs/relay-v2-envelope-findings.md` for the evidence trail.
public enum RelayV2KeySchedule {
    /// Two obfuscated constant blocks copied from the library's `.rodata`.
    ///
    /// They are not generated by anything in the app, so they have to be carried here
    /// verbatim. Both are mixed with a counter stream before use, which is why they do
    /// not appear anywhere in the library as literal key material.
    static let constantBlock1: [UInt8] = [
        0xc8, 0xe9, 0x35, 0xfb, 0x56, 0x2f, 0x68, 0xc9, 0xea, 0x4e, 0x05, 0xde, 0xd0, 0x79, 0xd1, 0xec,
        0x76, 0x2b, 0xbd, 0x1d, 0x38, 0xb5, 0xb9, 0x43, 0x9d, 0xcf, 0x80, 0xd5, 0x0b, 0xd2, 0xe6, 0x5c,
    ]

    static let constantBlock2: [UInt8] = [
        0xd4, 0x80, 0x76, 0x91, 0x64, 0x06, 0x7d, 0x96, 0xeb, 0xca, 0x82, 0x4a, 0xe1, 0x2d, 0xd1, 0xb6,
        0xb8, 0x25, 0x22, 0x8a, 0x3f, 0xdc, 0xbd, 0xd7, 0xda, 0x00, 0xb0, 0x19, 0x84, 0xcd, 0x10, 0x40,
    ]

    /// The process name the library reads from `/proc/self/cmdline`.
    ///
    /// It is part of the key, so an app with a different bundle identity derives a
    /// different session key.
    public static let defaultProcessIdentity: [UInt8] = Array("org.mewx.wenku8".utf8) + [0]

    /// A constant the library hashes and mixes in; its origin is a build-time tag.
    static let certificateTag = Array("wk8-fallback-cert-tag".utf8)

    /// The prefix mixed into the epoch label.
    static let epochLabel = Array("wk8-rne-epoch-".utf8) + [0]

    /// The first 32-byte block, mixed into the session-key message.
    ///
    /// `A[i] = ((0x5d * i) ^ (0xe3 + 0x97 * i)) ^ constantBlock1[i]`, all in bytes.
    public static func messagePrefix() -> [UInt8] {
        (0..<32).map { index in
            let a = UInt8(truncatingIfNeeded: 0x5d * index)
            let b = UInt8(truncatingIfNeeded: 0xe3 + 0x97 * index)
            return (a ^ b) ^ constantBlock1[index]
        }
    }

    /// The second 32-byte block, mixed into the working key.
    ///
    /// `B[i] = ((0x5d * i) ^ (0x55 + 0x0f * i)) ^ constantBlock2[i]`.
    public static func keyPrefix() -> [UInt8] {
        (0..<32).map { index in
            let a = UInt8(truncatingIfNeeded: 0x5d * index)
            let b = UInt8(truncatingIfNeeded: 0x55 + 0x0f * index)
            return (a ^ b) ^ constantBlock2[index]
        }
    }

    /// The working key the library stores after `init()`.
    ///
    /// `SHA256(processIdentity || SHA256(certificateTag) || keyPrefix())`.
    public static func workingKey(
        processIdentity: [UInt8] = defaultProcessIdentity
    ) -> [UInt8] {
        var material = processIdentity
        material += SHA256.hash(certificateTag)
        material += keyPrefix()
        return SHA256.hash(material)
    }

    /// The per-install session key, from the HKDF the library runs at `init()`.
    ///
    /// - Parameters:
    ///   - lut: the 2048-byte table bundled as `assets/wk8_lut.bin`.
    ///   - seed: the 32-byte seed derived from the app's constant arrays.
    ///   - flavor: 2 for the direct-download build, 1 for the Play Store build.
    public static func sessionKey(
        lut: [UInt8],
        seed: [UInt8],
        flavor: UInt8,
        processIdentity: [UInt8] = defaultProcessIdentity
    ) -> [UInt8] {
        let key = workingKey(processIdentity: processIdentity)
        var message = messagePrefix()
        message += SHA256.hash(lut)
        message += seed

        // Extract, then expand. The expand step deliberately has no block counter:
        // the official client calls HMAC once with a fixed label rather than the
        // RFC 5869 loop, and adding the counter byte produces a different key.
        let pseudoRandomKey = SHA256.hmac(key: key, message: message)
        var info = epochLabel
        info += [0xC9, flavor, 0x01]
        return SHA256.hmac(key: pseudoRandomKey, message: info)
    }
}
